import { lstatSync, readdirSync, realpathSync, statSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { readPlainText } from '../core/paths.js';

/**
 * agy's copy of a profile's CLAUDE.md (the owner's decision, 2026-11-21: CLAUDE.md stays the one instructions file).
 * Measured on agy 1.5.14 (ADR 0017, E): agy reads `<cwd>/AGENTS.md` and `<cwd>/GEMINI.md`, and expands
 * only the Markdown-link form `@[x](x.md)`, never Claude's bare `@path`. So Angelia writes the file
 * itself before every start, with Claude's imports expanded.
 *
 * The name is GEMINI.md, not AGENTS.md: only agy reads GEMINI.md, while Codex reads AGENTS.md instead
 * of CLAUDE.md and pi reads it first. A generated AGENTS.md left behind after a /backend switch would
 * shadow CLAUDE.md there with a stale copy.
 */
export const AGY_INSTRUCTIONS = 'GEMINI.md';

/** The folders in agy's --gemini-dir that agy loads code or settings from (red team round 2: a plugin
 *  with a hook planted in config/plugins ran on the next start, unasked), closed to writing after the
 *  folder itself is opened again (agySandboxProfile): the whole config/ (rules, MCP servers, skills,
 *  plugins, settings) and in antigravity-cli/ every folder of programs, servers, plugins, hooks,
 *  skills and knowledge, and its settings. Left writable: what agy writes as it works (conversations,
 *  brain, logs, caches, its databases and state files; measured 2026-11-21 on agy 1.5.14: it starts,
 *  answers and runs commands with these closed). The rules files at the top stay closed by name.
 *  `antigravity-cli/bin` cannot be closed: agy writes its shell helper there before each command
 *  (measured: closed, every run_command fails "failed to create bin directory"); the daemon removes
 *  it before each start instead (AGY_CLEARED), so nothing planted there outlives the session. */
export const AGY_CLEARED = [join('antigravity-cli', 'bin')];
export const AGY_CLOSED_DIRS = ['mcp', 'builtin', 'plugins', 'hooks', 'knowledge', 'skills', 'extensions'];
export function agyGeminiInputs(geminiDir: string): string[] {
  return [join(geminiDir, 'GEMINI.md'), join(geminiDir, 'AGENTS.md'), join(geminiDir, 'config', '**'),
    join(geminiDir, 'antigravity-cli', 'settings.json'), ...AGY_CLOSED_DIRS.map((d) => join(geminiDir, 'antigravity-cli', d, '**'))];
}

/** What agy 1.5.14 writes to config/config.json on its first start: the one plugin it ships. Angelia
 *  writes it before a sandboxed start, where the file is closed to writing. */
export const AGY_CONFIG_DEFAULT = '{\n  "plugins": {\n    "swarm": {\n      "enabled": true\n    }\n  }\n}';

/** The first line of the generated file. A GEMINI.md without it is someone's own, and never overwritten. */
export const AGY_HEADER = '<!-- Generated by Angelia from CLAUDE.md before every agy start. Do not edit this file: change CLAUDE.md, it is rewritten from there. -->';

/** Said first, in plain text under the header: a subagent's request often comes after the turn ends,
 *  when nothing can answer it but a refusal (ADR 0017, H; AgyBrain.watchForChild). */
export const AGY_TOOL_RULE = 'Do tool work yourself; do not use invoke_subagent, swarm or run_workflow for it: their permission requests often come after the turn ends and are refused.';

/** Claude's limit on nested imports (memory docs: at most five hops). */
export const MAX_IMPORT_DEPTH = 5;
/** One imported file larger than this is left out: no instruction file is that big. */
const MAX_IMPORT_BYTES = 1 << 20;

/** What agy itself has that Angelia cannot gate (ADR 0017, H): these never ask permission. */
export const AGY_UNGATED_TOOLS = ['invoke_subagent', 'define_subagent', 'manage_subagents', 'swarm', 'run_workflow', 'schedule'];

const TAIL = [
  '',
  '## Tools not to use here',
  '',
  `Do not use ${AGY_UNGATED_TOOLS.join(', ')}. They run without asking the owner, and their own tool requests cannot be answered in this chat. Do the work yourself in this session.`,
];

export function isGenerated(text: string): boolean {
  return text.startsWith(AGY_HEADER);
}

export interface ExpandOptions {
  home?: string;
  /** May the agent read this file? A denied import is left out: compile runs outside every sandbox,
   *  and an `@~/.ssh/id_ed25519` line written into CLAUDE.md must not copy the key into the folder. */
  readable?: (abs: string) => boolean;
}

/** Claude's import token: `@` at the start of a line or after a space, then a path with no space. */
const TOKEN = /(^|\s)@((?:[^\s\\`]|\\ )+)/g;

function target(raw: string, from: string, home: string): string | undefined {
  const p = raw.replace(/\\ /g, ' ');
  if (p === '~' || p.startsWith('~/')) return join(home, p.slice(1));
  if (isAbsolute(p)) return resolve(p);
  return resolve(dirname(from), p);
}

function readImport(abs: string, o: Required<ExpandOptions>): { text: string; real: string } | 'denied' | undefined {
  let real: string;
  try { real = realpathSync(abs); } catch { return undefined; }
  if (!o.readable(abs) || !o.readable(real)) return 'denied';
  try {
    const st = statSync(real);
    if (!st.isFile() || st.size > MAX_IMPORT_BYTES) return undefined;
    // Opened non-blocking and checked again on the descriptor: a pipe swapped in after the stat
    // cannot hold the daemon (review 3, M1).
    return { text: readPlainText(real, { max: MAX_IMPORT_BYTES }), real };
  } catch { return undefined; }
}

/**
 * The file's text with every `@path` import replaced by that file's text, recursively, as Claude Code
 * reads it: relative to the importing file, `~` for home, at most five hops, none inside a code fence
 * or a code span. A path that is not a readable file is left as written (an e-mail handle, a mention).
 * An import on a line of its own replaces the line; one inside a sentence keeps the sentence and adds
 * the file after it. A file already being expanded (a cycle) is not expanded again.
 */
export function expandImports(file: string, text: string, opts: ExpandOptions = {}, depth = 0, stack: string[] = []): string {
  const o: Required<ExpandOptions> = { home: opts.home ?? homedir(), readable: opts.readable ?? (() => true) };
  const out: string[] = [];
  let fence: string | undefined;
  for (const line of text.split('\n')) {
    const f = /^\s*(`{3,}|~{3,})/.exec(line)?.[1];
    if (fence) { out.push(line); if (f && f[0] === fence[0] && f.length >= fence.length) fence = undefined; continue; }
    if (f) { fence = f; out.push(line); continue; }
    if (depth >= MAX_IMPORT_DEPTH || !line.includes('@')) { out.push(line); continue; }
    // Code spans are blanked (same length) so no token is found inside one.
    const scan = line.replace(/`[^`]*`/g, (s) => ' '.repeat(s.length));
    const added: string[] = [];
    let alone = false;
    for (const m of scan.matchAll(TOKEN)) {
      let raw = m[2];
      let abs = target(raw, file, o.home);
      // A sentence's full stop or comma after the path is not part of it.
      if (abs && !safeExists(abs)) { raw = raw.replace(/[.,;:!?)\]]+$/, ''); abs = raw ? target(raw, file, o.home) : undefined; }
      if (!abs) continue;
      const got = readImport(abs, o);
      if (!got) continue;
      if (got === 'denied') { added.push(`(The import @${raw} is left out: this profile may not read it.)`); }
      else if (stack.includes(got.real)) continue;
      else added.push(expandImports(got.real, got.text.replace(/\n+$/, ''), o, depth + 1, [...stack, got.real]));
      if (scan.trim() === `@${m[2]}`) alone = true;
    }
    if (!added.length) { out.push(line); continue; }
    if (!alone) out.push(line);
    out.push(...added);
  }
  return out.join('\n');
}

function safeExists(p: string): boolean {
  try { statSync(p); return true; } catch { return false; }
}

/** The whole generated file for one CLAUDE.md. */
export function agyInstructionsText(claudeMd: string, text: string, opts: ExpandOptions = {}): string {
  const real = (() => { try { return realpathSync(claudeMd); } catch { return resolve(claudeMd); } })();
  return [AGY_HEADER, AGY_TOOL_RULE, '', expandImports(claudeMd, text.replace(/\n+$/, ''), opts, 0, [real]), ...TAIL, ''].join('\n');
}

function present(p: string): boolean {
  try { lstatSync(p); return true; } catch { return false; }
}

/**
 * What agy would load at start that Angelia did not give it (ADR 0017, D and E), one line each; empty
 * means go. Checked at compile, by the launch guard and again just before agy starts:
 * - `.agents/mcp_config.json` in the folder or an add_dir: agy starts those servers on its own;
 *   `.agents/skills` there: agy loads those skills on its own.
 * - an AGENTS.md or GEMINI.md in a folder above the profile's (agy reads at least one level up), an
 *   AGENTS.md in the folder (agy reads it beside the generated file), a GEMINI.md there not made by Angelia.
 * - in the profile's --gemini-dir: GEMINI.md and config/GEMINI.md (rules for every session),
 *   config/mcp_config.json (servers), config/config.json beyond agy's default (plugins),
 *   antigravity-cli/settings.json (hooks), and in config/skills anything compile did not link (`skills`).
 */
export function agyLaunchProblems(cwd: string, addDirs: string[], geminiDir: string, skills?: string[], home = homedir()): string[] {
  const out: string[] = [];
  for (const d of [cwd, ...addDirs.map((x) => (x === '~' || x.startsWith('~/') ? join(home, x.slice(1)) : resolve(cwd, x)))]) {
    const f = join(d, '.agents', 'mcp_config.json');
    if (present(f)) out.push(`${f}: agy starts the MCP servers listed there on its own; remove the file (give a profile servers in the routing table)`);
    const skills = join(d, '.agents', 'skills');
    if (present(skills)) out.push(`${skills}: agy loads the skills there on its own; remove the folder (give a profile skills in the routing table)`);
  }
  for (let d = dirname(resolve(cwd)); ; d = dirname(d)) {
    for (const n of ['AGENTS.md', 'GEMINI.md']) if (present(join(d, n))) out.push(`${join(d, n)}: agy reads instruction files in the folders above the profile's too; move it away`);
    if (dirname(d) === d) break;
  }
  if (present(join(cwd, 'AGENTS.md'))) out.push(`${join(cwd, 'AGENTS.md')}: agy reads it beside CLAUDE.md; move what it says into CLAUDE.md and remove it`);
  const own = join(cwd, AGY_INSTRUCTIONS);
  if (present(own)) {
    let text = '';
    try { text = readPlainText(own, { follow: false, max: 1 << 20 }).slice(0, AGY_HEADER.length); } catch { /* unreadable: not ours either */ }
    if (!isGenerated(text)) out.push(`${own}: not written by Angelia, so it is never overwritten; agy's copy of CLAUDE.md goes there: move what it says into CLAUDE.md and remove it`);
  }
  for (const f of [join(geminiDir, 'GEMINI.md'), join(geminiDir, 'config', 'GEMINI.md')]) {
    if (present(f)) out.push(`${f}: agy loads it for every session of this profile, and Angelia writes none there; remove it`);
  }
  // agy makes this file itself on its first start, empty (measured 1.5.14): only servers in it count.
  const mcp = join(geminiDir, 'config', 'mcp_config.json');
  if (present(mcp) && mcpConfigServers(mcp) !== 0) out.push(`${mcp}: agy starts the MCP servers listed there for every session of this profile; Angelia gives servers in session/new only, so empty the file or remove it`);
  // Plugins (config/config.json) and settings (hooks among them) apply to every session: only agy's
  // own default may be there (red team R3).
  const conf = join(geminiDir, 'config', 'config.json');
  if (present(conf)) {
    let extra = true;
    try {
      const j = JSON.parse(readPlainText(conf) || '{}') as Record<string, any>;
      extra = Object.keys(j).some((k) => k !== 'plugins') || Object.keys(j.plugins ?? {}).some((n) => n !== 'swarm');
    } catch { /* unreadable: counted */ }
    if (extra) out.push(`${conf}: agy loads the plugins and settings there for every session of this profile, and Angelia gives none; remove the file`);
  }
  const settings = join(geminiDir, 'antigravity-cli', 'settings.json');
  if (present(settings) && (() => { try { return readPlainText(settings).trim() !== ''; } catch { return true; } })()) {
    out.push(`${settings}: agy applies these settings (hooks among them) to every session of this profile, and Angelia writes none there; remove it`);
  }
  // Anything else in config/ (a plugin folder with hooks, a second skills folder), or a folder of
  // programs, plugins or hooks in antigravity-cli/, is not Angelia's (red team round 2): agy may load it.
  let inConfig: string[] = [];
  try { inConfig = readdirSync(join(geminiDir, 'config')); } catch { /* none */ }
  for (const n of inConfig) if (!['mcp_config.json', 'config.json', 'skills', 'GEMINI.md'].includes(n)) out.push(`${join(geminiDir, 'config', n)}: agy may load it (plugins, hooks, skills) for every session of this profile, and Angelia put none there; remove it`);
  for (const d of AGY_CLOSED_DIRS) {
    const f = join(geminiDir, 'antigravity-cli', d);
    if (present(f)) out.push(`${f}: agy may load programs, plugins or hooks from it for every session of this profile, and Angelia put none there; remove it`);
  }
  if (skills) {
    let names: string[] = [];
    try { names = readdirSync(join(geminiDir, 'config', 'skills')); } catch { /* none */ }
    for (const n of names) if (!skills.includes(n)) out.push(`${join(geminiDir, 'config', 'skills', n)}: a skill compile did not put there; remove it`);
  }
  return out;
}

/** How many servers an agy mcp_config.json names: 0 for an empty file or `{}`; -1 when it cannot be read. */
export function mcpConfigServers(file: string): number {
  let text: string;
  try { text = readPlainText(file); } catch { return -1; }
  if (!text.trim()) return 0;
  try {
    const j = JSON.parse(text) as { mcpServers?: unknown };
    if (!j || typeof j !== 'object' || Array.isArray(j)) return -1;
    const s = j.mcpServers;
    if (s === undefined) return Object.keys(j).length ? -1 : 0;
    return s && typeof s === 'object' && !Array.isArray(s) ? Object.keys(s).length : -1;
  } catch { return -1; }
}
